const KEY = 'kiar.lang';
let lang = 'de';
try {
  const saved = localStorage.getItem(KEY);
  if (saved === 'de' || saved === 'en') lang = saved;
  else if (!navigator.language.toLowerCase().startsWith('de')) lang = 'en';
} catch { /* storage unavailable */ }

const listeners = new Set();

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, lang); } catch { /* ignore */ }
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * Adds a module's own texts (a game's in-game strings live next to its code, e.g. bike-text.js):
 * addStrings({ de: { key: '...' }, en: { key: '...' } }). Existing keys are not overwritten.
 */
export function addStrings(dict) {
  for (const l of ['de', 'en']) {
    for (const [k, v] of Object.entries(dict[l] ?? {})) if (!(k in STRINGS[l])) STRINGS[l][k] = v;
  }
}

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Picks the current language from a bilingual content object { de, en }.
export function L(obj) {
  return obj[lang];
}
